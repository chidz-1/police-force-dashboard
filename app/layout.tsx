import { Inter, Merriweather, JetBrains_Mono } from "next/font/google";
import type { Metadata } from "next";

import "./globals.css";
import AppProviders from "@/features/Providers/Components/Providers";
import DashboardSideBar from "@/features/ApplicationSidebar/components/Sidebar";
import { FilterChangeProvider } from "@/features/Providers/Components/FilterChangeProvider";
import getStopData from "@/utils/getStopData";
import { getAvailability } from "@/utils/stopAvailability";
import StopDataProvider from "@/features/Providers/Components/StopDataProvider";

const fontSans = Inter({
  subsets: ["latin"],
  variable: "--font-sans",
});

const fontSerif = Merriweather({
  subsets: ["latin"],
  variable: "--font-serif",
});

const fontMono = JetBrains_Mono({
  subsets: ["latin"],
  variable: "--font-mono",
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const availableMonthRange = await getAvailability();
  const stopData = await getStopData(availableMonthRange);

  return (
    <html lang="en">
      <body
        className={`${fontSans.variable} ${fontSerif.variable} ${fontMono.variable} antialiased`}
      >
        <AppProviders>
          <DashboardSideBar>
            <FilterChangeProvider>
              <StopDataProvider stopsData={stopData}>
                {children}
              </StopDataProvider>
            </FilterChangeProvider>
          </DashboardSideBar>
        </AppProviders>
      </body>
    </html>
  );
}
